"""Isolated Docker-local Greptime 1.2.1 + MinIO storage lifecycle bench.

Runs the SAME deterministic synthetic workload against the current tree
and --baseline-root, each in its own isolated Docker Compose project:
pinned Greptime + pinned MinIO binary + stdlib S3-meter sidecar, loopback
ports, fresh owned volumes and bucket, synthetic credentials per run
(never production env).

  python3 tools/benchmark_greptime_storage.py --baseline-root ROOT \
      --rows 20000 --json-out /tmp/greptime-bench.json \
      --budget config/cost-budget.json

Flags: --baseline-root ROOT (required; missing fails unless --no-baseline
bootstrap), --rows N (default 20000; nightly 10000000 streams in bounded
batches so it stays feasible), --json-out PATH (required),
--budget PATH (optional CostGate `greptime` section check), --no-baseline
(initial push only), --greptime-image (trusted pin override),
--minio-binary-url (test-only download-base override).

Lifecycle per variant: create bucket -> DDL (signal + hourly rollup) ->
ingest in 4 flush-separated segments (forces multiple SSTs) ->
ADMIN flush_table per segment (verified by S3 inventory) ->
ADMIN compact_table with polled native completion (S3 inventory stable +
full row count visible), never a blind sleep -> build hourly rollup from
DB GROUP BY, cross-checked against the deterministic fold -> stop only the
owned greptimedb service, clear its two persistent object caches, and start
the same container/volumes -> 20 Grafana-shaped cold queries (must show
successful SST GET bytes at the meter during the query window,
cold results recorded) -> 20 warm queries x2 (must reuse bytes, results
must equal cold). No File-storage fallback: any skipped
flush/compact/cold step is a hard failure with evidence JSON. Cleanup
stops/removes ONLY the owned project; residual `docker ps`/`volume ls`
is part of the evidence, including on failure.

Config source: the TOML is generated by running each variant tree's ACTUAL
scripts/database/greptime_preflight.py (cache/flush/storage keys all come
from that source, per variant). The sole bench-only line delta is recorded:
S3 endpoint must be plain-http to the in-network meter sidecar (preflight
only allows https, correct for production). Greptime 1.2.1 forces the S3
write cache on even when TOML says false; coldness is established by actual
offline cache deletion, not by a configuration override. Image pins come from each
tree's compose/core.yaml (greptime + python); MinIO stays the pinned
release binary below.

Networking: Greptime talks S3 to http://s3meter:9000 entirely inside the
owned Compose network (in-network DNS, no host-gateway, Linux-safe). The
host touches only loopback-mapped ports: Greptime :4000, MinIO :9000
(bucket create + inventory LIST bypass the meter), and the meter snapshot
port. Nothing is bound 0.0.0.0 to the host; the meter proxy port is never
published.
"""

