def _redact(text):
    """Redact synthetic credential values from diagnostic text."""
    out = text or ""
    for tok in re.findall(r"(?:bench[0-9a-f]{4,}|pw[0-9a-f]{8,}|"
                           r"adm[0-9a-f]{8,}|ot[0-9a-f]{8,}|"
                           r"s3cr3t[0-9a-f]{8,})", out):
        out = out.replace(tok, "<redacted>")
    return out[-4000:]


def _startup_diag(tmp, project, env, evidence, note):
    """Capture owned-container status/logs BEFORE teardown (redacted)."""
    diag = {"note": note}
    try:
        rc, out, err = compose_run(tmp, project, env, "ps", "--all",
                                   "--format", "json", timeout=60)
        diag["ps_rc"] = rc
        diag["ps"] = _redact(out[-2000:] if rc == 0 else err[-2000:])
    except Exception as e:  # noqa: BLE001 - diagnostics never mask cause
        diag["ps_error"] = str(e)[:200]
    for svc in ("greptimedb", "s3meter", "minio"):
        try:
            rc, out, err = compose_run(tmp, project, env, "logs",
                                       "--no-color", "--tail", "80", svc,
                                       timeout=60)
            diag["logs_%s_rc" % svc] = rc
            diag["logs_%s" % svc] = _redact(
                out[-2000:] if rc == 0 else err[-2000:])
        except Exception as e:  # noqa: BLE001
            diag["logs_%s_error" % svc] = str(e)[:200]
    try:
        with open(os.path.join(tmp, "greptimedb.toml"), encoding="utf-8") as f:
            diag["config"] = _redact(f.read())
    except OSError as e:
        diag["config_error"] = _redact(str(e))
    diag["auth_file_present"] = os.path.isfile(os.path.join(tmp, "preflight", "auth", "users"))
    diag["ports"] = dict(env)
    evidence["startup_diag"] = diag
    return diag


