def owned_cache_scope(tmp, project, env):
    """Fail closed before stopping or mounting any volume for mutation."""
    if not re.fullmatch(r"gbench-gbench[0-9]+", project):
        raise RuntimeError("cache reset requires an owned synthetic project")
    with open(os.path.join(tmp, "greptimedb.toml"), encoding="utf-8") as source:
        config_text = source.read()
    layout = cache_config(config_text)
    containers, volumes, identities, running = {}, {}, {}, {}
    for service in ("greptimedb", "minio", "s3meter"):
        rc, out, _ = compose_run(tmp, project, env, "ps", "--all", "--quiet", service)
        ids = out.splitlines()
        if rc or len(ids) != 1 or not re.fullmatch(r"[0-9a-f]{12,64}", ids[0]):
            raise RuntimeError("cache reset cannot identify sole owned service")
        container_id = ids[0]
        rc, out, _ = sh(["docker", "inspect", container_id])
        if rc:
            raise RuntimeError("cache reset container inspection failed")
        obj, = json.loads(out)
        labels = obj["Config"].get("Labels") or {}
        if (labels.get("com.docker.compose.project") != project
                or labels.get("com.docker.compose.service") != service):
            raise RuntimeError("cache reset container ownership mismatch")
        containers[service] = obj["Id"]
        running[service] = obj["State"]["Running"]
        if service == "s3meter":
            continue
        mounts = obj["Mounts"]
        data = [m for m in mounts if m["Destination"] == "/data"]
        if (len(data) != 1 or data[0]["Type"] != "volume" or not data[0]["RW"]
                or any(m["Destination"].startswith("/data/") for m in mounts)):
            raise RuntimeError("cache reset refuses unknown data mounts")
        if service == "greptimedb":
            expected = {"/etc/greptime/greptimedb.toml": os.path.join(tmp, "greptimedb.toml"),
                        "/etc/greptime/auth": os.path.join(tmp, "preflight", "auth")}
            for destination, source in expected.items():
                matched = [m for m in mounts if m["Destination"] == destination]
                if len(matched) != 1 or matched[0]["Type"] != "bind" or matched[0]["RW"]:
                    raise RuntimeError("cache reset config/auth mount mismatch")
                mounted = os.path.realpath(matched[0]["Source"])
                if mounted != os.path.realpath(source):
                    if (destination != "/etc/greptime/greptimedb.toml"
                            or os.path.dirname(mounted) != os.path.realpath(tmp)
                            or not re.fullmatch(r"greptimedb-config-[a-z0-9_]+\.toml", os.path.basename(mounted))
                            or os.path.islink(matched[0]["Source"])):
                        raise RuntimeError("cache reset config/auth mount mismatch")
                    with open(mounted, encoding="utf-8") as immutable:
                        if immutable.read() != config_text:
                            raise RuntimeError("cache reset mounted configuration differs")
        name = data[0]["Name"]
        rc, out, _ = sh(["docker", "volume", "inspect", name])
        if rc:
            raise RuntimeError("cache reset volume inspection failed")
        volume, = json.loads(out)
        labels = volume.get("Labels") or {}
        expected_name = "greptime-data" if service == "greptimedb" else "minio-data"
        if (volume["Name"] != name or volume.get("Driver") != "local"
                or volume.get("Options")
                or labels.get("com.docker.compose.project") != project
                or labels.get("com.docker.compose.volume") != expected_name):
            raise RuntimeError("cache reset volume scope mismatch")
        rc, out, _ = sh(["docker", "ps", "-a", "--filter", "volume=" + name,
                         "--format", "{{.ID}}"])
        consumers = out.splitlines()
        if rc or len(consumers) != 1 or not obj["Id"].startswith(consumers[0]):
            raise RuntimeError("cache reset refuses shared volume")
        role = "greptime" if service == "greptimedb" else "minio"
        volumes[role] = name
        identities[role] = hashlib.sha256(name.encode()).hexdigest()
    if volumes["greptime"] == volumes["minio"]:
        raise RuntimeError("cache reset refuses mixed primary/cache volumes")
    return {"containers": containers, "volume_ids": identities,
            "running": running, "layout": layout}


def reset_owned_cache(tmp, project, env, evidence):
    before = owned_cache_scope(tmp, project, env)
    if not all(before["running"].values()):
        raise RuntimeError("cache reset expects all owned services running")
    rc, _, _ = compose_run(tmp, project, env, "stop", "--timeout", "60", "greptimedb",
                           timeout=120)
    if rc:
        raise RuntimeError("owned Greptime stop failed")
    stopped = owned_cache_scope(tmp, project, env)
    if (stopped["containers"] != before["containers"]
            or stopped["volume_ids"] != before["volume_ids"]
            or stopped["layout"] != before["layout"]
            or stopped["running"]["greptimedb"]
            or not stopped["running"]["minio"] or not stopped["running"]["s3meter"]):
        raise RuntimeError("cache reset stop/ownership invariant failed")
    ids = before["volume_ids"]
    with open(os.path.join(tmp, "greptimedb.toml"), encoding="utf-8") as source:
        config = source.read()
    rc, out, _ = compose_run(
        tmp, project, env, "run", "--rm", "--no-deps", "-T",
        "-e", "CACHE_GREPTIME_VOLUME_ID=" + ids["greptime"],
        "-e", "CACHE_MINIO_VOLUME_ID=" + ids["minio"], "cache-reset",
        timeout=300, input=config)
    if rc:
        raise RuntimeError("owned cache helper refused mutation")
    result = json.loads(out)
    if (result.get("preserved_volume_ids") != ids
            or [r["cache_dir"] for r in result.get("cache_dirs", [])] != list(CACHE_DIRS)
            or any(type(result.get(k)) is not int or result[k] < 0
                   for k in ("deleted_files", "deleted_bytes"))):
        raise RuntimeError("owned cache helper evidence mismatch")
    evidence["cache_reset"] = result
    evidence["cache_reset"]["layout"] = before["layout"]
    after = owned_cache_scope(tmp, project, env)
    if after != stopped:
        raise RuntimeError("cache reset changed owned resources")
    rc, _, _ = compose_run(tmp, project, env, "start", "greptimedb", timeout=300)
    if rc:
        raise RuntimeError("owned Greptime start failed")
    restarted = owned_cache_scope(tmp, project, env)
    if (restarted["containers"] != before["containers"]
            or restarted["volume_ids"] != ids or not all(restarted["running"].values())):
        raise RuntimeError("cache reset did not preserve owned service/volume identity")


def sst_query_delta(before, after, require_cold=False):
    """Cumulative successful SST payload counters, not a bounded request tail."""
    result = {}
    for key in ("sst_get_requests", "sst_read_bytes"):
        a, b = before["counters"].get(key), after["counters"].get(key)
        if type(a) is not int or type(b) is not int or a < 0 or b < a:
            raise RuntimeError("missing/invalid cumulative successful SST counter")
        result[key] = b - a
    if require_cold and (result["sst_get_requests"] <= 0 or result["sst_read_bytes"] <= 0):
        raise RuntimeError("cold query window produced no successful SST GET payload")
    return result


def meter_error_diagnostics(snapshot):
    """Persist only non-sensitive status/op/object-kind/count/byte evidence."""
    groups = {}
    kinds = {"sst", "control", "manifest_checkpoint_discovery", "drop_marker"}
    ops = {"GET", "HEAD", "PUT", "LIST", "DELETE", "POST", "COPY", "UPLOAD_PART",
           "CREATE_MP", "COMPLETE_MP", "ABORT_MP"}
    for request in snapshot.get("requests", []):
        status = request.get("status")
        if type(status) is not int or not 400 <= status < 500:
            continue
        op = request.get("op")
        kind = request.get("object_kind")
        expected = request.get("expected_not_found") is True
        key = (status, op if op in ops else "unknown", kind if kind in kinds else "unknown", expected)
        row = groups.setdefault(key, {"status": key[0], "op": key[1],
                                      "object_kind": key[2], "expected_not_found": key[3],
                                      "requests": 0, "bytes": 0})
        row["requests"] += 1
        for field in ("req_bytes", "resp_bytes"):
            value = request.get(field)
            if type(value) is int and value >= 0:
                row["bytes"] += value
    cumulative = []
    for source in snapshot.get("client_error_breakdown", []):
        status = source.get("status")
        op, kind = source.get("op"), source.get("object_kind")
        row = {"status": status if type(status) is int and 400 <= status < 500 else None,
               "op": op if op in ops else "unknown",
               "object_kind": kind if kind in kinds else "unknown",
               "expected_not_found": source.get("expected_not_found") is True}
        for field in ("requests", "bytes"):
            value = source.get(field)
            row[field] = value if type(value) is int and value >= 0 else None
        cumulative.append(row)
    counters = snapshot.get("counters", {})
    summary = {}
    for key in ("client_errors", "client_error_bytes", "expected_not_found_requests",
                "expected_not_found_bytes", "errors", "truncated", "unsupported"):
        value = counters.get(key)
        summary[key] = value if type(value) is int and value >= 0 else None
    return {"cumulative": summary, "cumulative_client_error_breakdown": cumulative,
            "sample_complete": snapshot.get("truncated_requests") == 0,
            "sample_client_error_breakdown": [groups[key] for key in sorted(groups)]}


def validate_meter_errors(snapshot):
    """Allow only producer-classified source-proven discovery misses.

    Greptime 1.2.1 optional checkpoint NotFound returns None:
    https://github.com/GreptimeTeam/greptimedb/blob/179ff8e5099d35e217a5ffeb6e4096405824dd6c/src/mito2/src/manifest/storage/checkpoint.rs#L194-L205
    Region-open also checks the optional .dropping marker with exists():
    https://github.com/GreptimeTeam/greptimedb/blob/179ff8e5099d35e217a5ffeb6e4096405824dd6c/src/mito2/src/worker/handle_open.rs#L148-L155
    The meter must positively classify these misses. A generic control404,
    failed SST, auth error, malformed response, or unknown client error
    cannot receive this allowance. Every request/body byte remains billed.
    """
    counters = snapshot["counters"]
    fields = ("client_errors", "client_error_bytes", "expected_not_found_requests",
              "expected_not_found_bytes", "errors", "copy_unknown", "truncated", "unsupported")
    for key in fields:
        value = counters.get(key)
        if type(value) is not int or value < 0:
            raise RuntimeError("missing/invalid S3 meter error counter " + key)
    expected = counters["expected_not_found_requests"]
    expected_bytes = counters["expected_not_found_bytes"]
    if (expected > counters["client_errors"]
            or expected_bytes > counters["client_error_bytes"]
            or (expected == 0 and expected_bytes != 0)):
        raise RuntimeError("inconsistent S3 discovery-miss accounting")
    unexpected = counters["client_errors"] - expected
    if unexpected:
        raise RuntimeError("S3 meter recorded unexpected_client_errors=%d" % unexpected)
    if expected_bytes != counters["client_error_bytes"]:
        raise RuntimeError("unclassified S3 client-error bytes")
    for key in ("errors", "copy_unknown", "truncated", "unsupported"):
        if counters[key]:
            raise RuntimeError("S3 meter recorded %s=%s" % (key, counters[key]))
    return {"expected_not_found_requests": expected,
            "expected_not_found_bytes": expected_bytes,
            "unexpected_client_errors": unexpected}


def _num(x):
    """Greptime /v1/sql returns numbers as JSON strings; coerce, None stays."""
    if x is None or isinstance(x, bool):
        return None
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(v) else v


def _to_ms(x):
    """Normalize a date_bin bucket value to epoch millis int; None if unknown."""
    if x is None or isinstance(x, bool):
        return None
    if isinstance(x, (int, float)):
        v = float(x)
        if math.isnan(v):
            return None
        if v >= 1e11:
            return int(v)  # already millis (nanos would be >= 1e17; unsupported)
        if v >= 1e8:
            return int(v * 1000)  # epoch seconds
        return None
    if isinstance(x, str):
        s = x.strip().replace("T", " ").rstrip("Z").strip()
        for fmt in ("%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%d %H:%M:%S",
                    "%Y-%m-%d %H:%M", "%Y-%m-%d"):
            try:
                dt = datetime.datetime.strptime(s.split("+")[0].strip(), fmt)
                return int(dt.replace(tzinfo=datetime.timezone.utc).timestamp()
                           * 1000)
            except ValueError:
                continue
        return None
    return None


def _cell_equal(exp, got):
    if exp is None:
        return got is None
    if isinstance(exp, int) and not isinstance(exp, bool):
        return _to_ms(got) == exp if isinstance(got, str) else (
            got is not None and _num(got) is not None
            and float(_num(got)) == float(exp))
    if isinstance(exp, float):
        g = _num(got)
        return g is not None and (
            float(g) == float(exp)
            or abs(float(g) - float(exp)) <= 1e-6 * max(1.0, abs(float(exp))))
    if isinstance(exp, str):
        return got == exp
    if isinstance(exp, list):
        return (isinstance(got, (list, tuple)) and len(got) == len(exp)
                and all(_cell_equal(e, g) for e, g in zip(exp, got)))
    return got == exp


def _got_equal(a, b):
    """Cold-vs-warm result equality (floats tolerate last-ulp regrouping)."""
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(_got_equal(x, y) for x, y in zip(a, b))
    if isinstance(a, bool) or isinstance(b, bool):
        return a == b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return float(a) == float(b) or abs(float(a) - float(b)) <= (
            1e-12 * max(1.0, abs(float(a)), abs(float(b))))
    return a == b


def run_queries(base, queries, auth=None):
    """Execute the 20 oracle queries; return per-query row/result evidence."""
    out = []
    for name, sql, expected, kind in queries:
        t0 = time.time()
        recs = grecords(base, sql, auth=auth)
        ms = (time.time() - t0) * 1000.0
        rows = [list(d.values()) for d in recs]
        if kind == "scalar":
            got = _num(rows[0][0]) if rows and len(rows[0]) else None
            ok = _cell_equal(expected, got)
        elif kind == "tuple":
            got = [_num(c) for c in rows[0]] if rows and len(rows[0]) else []
            ok = (len(got) == len(expected)
                  and all(_cell_equal(e, g) for e, g in zip(expected, got)))
        elif kind == "rows":
            got = rows
            ok = (len(got) == len(expected)
                  and all(len(g) == len(e) and
                          all(_cell_equal(ce, cg) for ce, cg in zip(e, g))
                          for e, g in zip(expected, got)))
        else:
            raise RuntimeError("unknown oracle kind %s" % kind)
        out.append({"name": name, "sql": sql, "expected": expected, "got": got,
                    "oracle_pass": bool(ok), "ms": round(ms, 1),
                    "rows": len(rows)})
    return out


