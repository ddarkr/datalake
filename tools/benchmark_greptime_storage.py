def compaction_metrics(base, auth):
    """Completed histogram increments only after the native worker applies its edit.

    Greptime 1.2.1 CompactionFinished.on_success observes the histogram;
    neither scheduling a task nor uploading an unfinished file does so.
    """
    import base64
    headers = {"Authorization": "Basic " + base64.b64encode(
        ("%s:%s" % auth).encode()).decode()}
    req = urllib.request.Request(base + "/metrics", headers=headers)
    with urllib.request.urlopen(req, timeout=30) as r:
        text = r.read().decode()
    names = {"completed": "greptime_mito_compaction_total_elapsed_count",
             "failures": "greptime_mito_compaction_failure_total",
             "inflight": "greptime_mito_inflight_compaction_count"}
    values = {}
    for key, name in names.items():
        match = re.search(r"^" + re.escape(name) + r"\s+([^\s]+)", text, re.M)
        # Counters are lazy-registered. A missing pre-task value is zero;
        # completion cannot pass without the post-task histogram advancing.
        value = float(match.group(1)) if match else 0.0
        if not math.isfinite(value) or value < 0:
            raise RuntimeError("bad native compaction metric %s" % name)
        values[key] = value
    return values


def compaction_completed(before, after, before_files, after_files):
    return (after["completed"] > before["completed"]
            and after["failures"] == before["failures"]
            and after["inflight"] == 0
            and bool(after_files - before_files))


def cleanup_project(tmp, project, env, evidence):
    """Remove/check every owned resource; preserve recovery files on failure."""
    errors = []
    if os.path.isfile(os.path.join(tmp, "docker-compose.yaml")):
        try:
            rc, _, err = compose_run(tmp, project, env, "down", "-v", "--remove-orphans")
            if rc:
                errors.append("compose down rc=%s: %s" % (rc, _redact(err)))
        except Exception as e:
            errors.append("compose down: " + _redact(str(e)))
    residuals = {}
    filt = "label=com.docker.compose.project=%s" % project
    commands = {"containers": ["docker", "ps", "-a", "--filter", filt, "--format", "{{.ID}}"],
                "volumes": ["docker", "volume", "ls", "--filter", filt, "--format", "{{.Name}}"],
                "networks": ["docker", "network", "ls", "--filter", filt, "--format", "{{.ID}}"]}
    for kind, command in commands.items():
        try:
            rc, out, err = sh(command)
            if rc:
                errors.append("inspect %s rc=%s: %s" % (kind, rc, _redact(err)))
                residuals[kind] = ["inspection-failed"]
                continue
            ids = out.splitlines()
            if ids:
                delete = (["docker", "rm", "-f"] if kind == "containers" else
                          ["docker", "volume", "rm"] if kind == "volumes" else
                          ["docker", "network", "rm"])
                rc, _, err = sh(delete + ids)
                if rc:
                    errors.append("remove %s rc=%s: %s" % (kind, rc, _redact(err)))
                rc, out, err = sh(command)
                if rc:
                    errors.append("reinspect %s rc=%s: %s" % (kind, rc, _redact(err)))
                    out = "inspection-failed"
            residuals[kind] = out.splitlines()
        except Exception as e:
            errors.append("cleanup %s: %s" % (kind, _redact(str(e))))
            residuals[kind] = ["inspection-failed"]
    success = not errors and not any(residuals.values())
    if success:
        try:
            shutil.rmtree(tmp)
        except OSError as e:
            errors.append("remove recovery files: " + _redact(str(e)))
            success = False
    evidence["cleanup"] = {"success": success, "errors": errors,
                           "residual_containers": residuals.get("containers", []),
                           "residual_volumes": residuals.get("volumes", []),
                           "residual_networks": residuals.get("networks", [])}
    if not success:
        evidence["cleanup"].update(recovery_dir=tmp, project=project, ports=dict(env))
    return residuals.get("volumes", []), residuals.get("containers", [])


