def fixture_row(i, rows):
    """Bounded deterministic generation with unique 10M-fixture primary keys.

    Multiplication by 7 modulo 21,600,000 is a permutation. Each of the
    four disjoint six-hour segments has fewer than that many indices at
    10M rows, so timestamps within a segment cannot repeat.
    """
    per = rows // SEGMENTS
    seg = min(i // per, SEGMENTS - 1) if per else SEGMENTS - 1
    v = i % len(VEHICLES)
    p = (i // len(VEHICLES)) % len(PATHS)
    stamp = BASE_MS + seg * 6 * HOUR_MS + (i * 7) % (6 * HOUR_MS)
    value = ((i * 7919) % 10000) / 100.0 + v * 10.0
    return seg, VEHICLES[v], PATHS[p], stamp, value


def _fold(st, vehicle, path, value, seg, ts_ms):
    st["n"] += 1
    st["sum"] += value
    st["min"] = value if st["min"] is None else min(st["min"], value)
    st["max"] = value if st["max"] is None else max(st["max"], value)
    vb = st["by_vehicle"].setdefault(vehicle, [0, 0.0])
    vb[0] += 1
    vb[1] += value
    pb = st["by_path"].setdefault(path, [0, 0.0])
    pb[0] += 1
    pb[1] += value
    sb = st["by_seg"].setdefault(seg, [0, 0.0])
    sb[0] += 1
    sb[1] += value
    b1 = BASE_MS + ((ts_ms - BASE_MS) // HOUR_MS) * HOUR_MS
    bb = st["by_bin"].setdefault(b1, [0, 0.0])
    bb[0] += 1
    bb[1] += value
    if vehicle == "v0":
        st["sum_v0"] += value
        b6 = BASE_MS + ((ts_ms - BASE_MS) // (6 * HOUR_MS)) * (6 * HOUR_MS)
        b6b = st["by_bin6_v0"].setdefault(b6, [0, 0.0])
        b6b[0] += 1
        b6b[1] += value
    if path == "p1":
        st["tag_p1"][0] += 1
        st["tag_p1"][1] += value
    if seg in (0, 1):
        st["lr"][0] += 1
        st["lr"][1] += value
    if value > 50.0:
        st["over"] += 1
    st["groups"].add((vehicle, path))
    rk = st["rollup"].setdefault((b1, vehicle, path), [0, 0.0])
    rk[0] += 1
    rk[1] += value


