def fetch_minio_binary(tmp):
    """Stdlib-download the pinned official MinIO binary, verify SHA256.

    Returns the bind path. Any mismatch or download failure is fatal:
    there is no image fallback (registry tags verified unavailable).
    """
    import platform
    arch = {"x86_64": "amd64", "aarch64": "arm64", "arm64": "arm64"}.get(
        platform.machine(), "amd64")
    name = "minio.linux-%s.%s" % (arch, MINIO_RELEASE)
    url = "%s/%s" % (MINIO_BASE, name)
    dest = os.path.join(tmp, "minio-bin")
    req = urllib.request.Request(url, headers={"User-Agent": "datalake-bench/1"})
    digest = hashlib.sha256()
    with urllib.request.urlopen(req, timeout=600) as r, \
            open(dest, "wb") as f:
        while True:
            chunk = r.read(65536)
            if not chunk:
                break
            digest.update(chunk)
            f.write(chunk)
    if digest.hexdigest() != MINIO_SHA256[arch]:
        os.unlink(dest)
        raise RuntimeError("minio binary SHA256 mismatch for %s" % name)
    os.chmod(dest, 0o755)
    return dest


