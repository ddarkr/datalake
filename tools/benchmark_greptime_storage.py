        # Warm twice: second passes must reuse (fewer bytes); spread
        # recorded as measurement uncertainty, never ignored. Results must
        # equal cold exactly (same stored bytes, no staleness).
        warm1 = run_queries(base, queries, auth)
        snap2 = snap_get(snap_port)
        warm2 = run_queries(base, queries, auth)
        snap3 = snap_get(snap_port)
        c2, c3 = snap2["counters"], snap3["counters"]
        warm_sst1 = sst_query_delta(snap1, snap2)
        warm_sst2 = sst_query_delta(snap2, snap3)
        w1 = {"requests": c2["requests"] - c1["requests"],
              "read_bytes": c2["read_bytes"] - c1["read_bytes"]}
        w2 = {"requests": c3["requests"] - c2["requests"],
              "read_bytes": c3["read_bytes"] - c2["read_bytes"]}
