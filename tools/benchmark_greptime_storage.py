        if not flushed:
            raise RuntimeError("no SST objects after flush: cold/warm meaningless")
        # Four disjoint six-hour flushes may need no regular TWCS merge.
        # Manual SWCS covers all of them in one day-sized window.
        pre_set = {k for k, _ in flushed if k.endswith(".parquet")}
        if len(pre_set) < 2:
            raise RuntimeError("fixture did not produce multiple SSTs")
        before_compact = compaction_metrics(base, auth)
        compact_out = gsql(base, "ADMIN compact_table('%s', 'swcs', 'window=86400')" % TABLE,
                           timeout=300, auth=auth)
        stable, last = 0, None
