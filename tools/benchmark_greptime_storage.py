def build_queries(st):
    """20 Grafana-shaped oracle queries: (name, sql, expected, kind).

    Kinds: "scalar" (one number), "tuple" (one row of numbers),
    "rows" (full ordered row list; group/bin values, not just lengths).
    Tolerates stats dicts missing the newer keys (degenerate expectations).
    """
    n = st.get("n", 0)
    by_v = st.get("by_vehicle", {})
    by_s = st.get("by_seg", {})
    total = float(st.get("sum", 0.0))
    mn = st.get("min")
    mx = st.get("max")
    q = [("total_count", "SELECT COUNT(*) FROM %s" % TABLE, float(n), "scalar")]
    for veh in VEHICLES:
        q.append(("count_%s" % veh,
                  "SELECT COUNT(*) FROM %s WHERE vehicle='%s'" % (TABLE, veh),
                  float(by_v.get(veh, [0])[0]), "scalar"))
    q.append(("avg_all", "SELECT AVG(value_num) FROM %s" % TABLE,
              total / n if n else 0.0, "scalar"))
    q.append(("min_max", "SELECT MIN(value_num), MAX(value_num) FROM %s" % TABLE,
              [mn if mn is not None else 0.0, mx if mx is not None else 0.0],
              "tuple"))
    q.append(("sum_all", "SELECT SUM(value_num) FROM %s" % TABLE, total, "scalar"))
    c0, s0 = by_s.get(0, [0, 0.0])
    lo0 = (BASE_TS).strftime("%Y-%m-%d %H:%M:%S")
    hi0 = (BASE_TS + datetime.timedelta(hours=6)).strftime("%Y-%m-%d %H:%M:%S")
    q.append(("count_seg0",
              "SELECT COUNT(*) FROM %s WHERE event_time>='%s' AND event_time<'%s'"
              % (TABLE, lo0, hi0), float(c0), "scalar"))
    c3, s3 = by_s.get(SEGMENTS - 1, [0, 0.0])
    lo3 = (BASE_TS + datetime.timedelta(hours=6 * (SEGMENTS - 1))).strftime(
        "%Y-%m-%d %H:%M:%S")
    hi3 = (BASE_TS + datetime.timedelta(hours=6 * SEGMENTS)).strftime(
        "%Y-%m-%d %H:%M:%S")
    q.append(("avg_seg3",
              "SELECT AVG(value_num) FROM %s WHERE event_time>='%s' AND event_time<'%s'"
              % (TABLE, lo3, hi3), s3 / c3 if c3 else 0.0, "scalar"))
    # Full (vehicle, path, count, avg) values, not just the group count.
    gsum = {}
    for (veh, path) in st.get("groups", set()):
        gsum[(veh, path)] = [0, 0.0]
    for (b1, veh, path), (c, s) in st.get("rollup", {}).items():
        g = gsum.setdefault((veh, path), [0, 0.0])
        g[0] += c
        g[1] += s
    groups = sorted([[veh, path, float(c), s / c if c else 0.0]
                     for (veh, path), (c, s) in gsum.items()])
    q.append(("groups_full",
              "SELECT vehicle, path, COUNT(*), AVG(value_num) FROM %s "
              "GROUP BY vehicle, path ORDER BY vehicle, path" % TABLE,
              groups, "rows"))
    bins = sorted([[b, float(c), s / c if c else 0.0]
                   for b, (c, s) in st.get("by_bin", {}).items()])
    q.append(("datebin_hours",
              "SELECT %s AS b, COUNT(*), AVG(value_num) FROM %s "
              "GROUP BY %s ORDER BY b" % (BIN1H, TABLE, BIN1H),
              bins, "rows"))
    bins6 = sorted([[b, float(c), s / c if c else 0.0]
                    for b, (c, s) in st.get("by_bin6_v0", {}).items()])
    q.append(("datebin_v0_6h",
              "SELECT %s AS b, COUNT(*), AVG(value_num) FROM %s "
              "WHERE vehicle='v0' GROUP BY %s ORDER BY b" % (BIN6H, TABLE, BIN6H),
              bins6, "rows"))
    tp = st.get("tag_p1", [0, 0.0])
    q.append(("tagfilter_p1",
              "SELECT COUNT(*), AVG(value_num) FROM %s "
              "WHERE source='bench' AND path='p1'" % TABLE,
              [float(tp[0]), tp[1] / tp[0] if tp[0] else 0.0], "tuple"))
    roll = sorted(st.get("rollup", {}).items())
    q.append(("rollup_rowcount", "SELECT COUNT(*) FROM %s" % ROLLUP,
              float(len(roll)), "scalar"))
    if roll:
        (sb, sv, sp), (sc, ss) = roll[0]
        sbs = (datetime.datetime.fromtimestamp(sb / 1000,
                                              tz=datetime.timezone.utc)
               .strftime("%Y-%m-%d %H:%M:%S"))
        q.append(("rollup_spot",
                  "SELECT cnt, sum_v FROM %s WHERE bucket_start='%s' AND "
                  "vehicle='%s' AND path='%s'" % (ROLLUP, sbs, sv, sp),
                  [float(sc), ss], "tuple"))
    else:
        q.append(("rollup_spot",
                  "SELECT cnt, sum_v FROM %s WHERE 1=0" % ROLLUP,
                  [0.0, 0.0], "tuple"))
    lr = st.get("lr", [0, 0.0])
    lr_avg = lr[1] / lr[0] if lr[0] else 0.0
    hi12 = (BASE_TS + datetime.timedelta(hours=12)).strftime("%Y-%m-%d %H:%M:%S")
    q.append(("longrange_raw_avg",
              "SELECT AVG(value_num) FROM %s WHERE event_time>='%s' AND "
              "event_time<'%s'" % (TABLE, lo0, hi12), lr_avg, "scalar"))
    q.append(("longrange_rollup_avg",
              "SELECT SUM(sum_v)/SUM(cnt) FROM %s WHERE bucket_start>='%s' AND "
              "bucket_start<'%s'" % (ROLLUP, lo0, hi12), lr_avg, "scalar"))
    q.append(("over50", "SELECT COUNT(*) FROM %s WHERE value_num>50" % TABLE,
              float(st.get("over", 0)), "scalar"))
    q.append(("sum_v0", "SELECT SUM(value_num) FROM %s WHERE vehicle='v0'" % TABLE,
              st.get("sum_v0", 0.0), "scalar"))
    assert len(q) == 20, len(q)
    return q


# ---- Greptime HTTP SQL client (stdlib; same shape as tools/demo.py) ----

def gsql(base, sql, timeout=120, auth=None):
    body = urllib.parse.urlencode({"sql": sql}).encode()
    headers = {"Content-Type": "application/x-www-form-urlencoded"}
    if auth is not None:
        import base64
        user, password = auth
        headers["Authorization"] = "Basic " + base64.b64encode(
            ("%s:%s" % (user, password)).encode()).decode()
    req = urllib.request.Request(base + "/v1/sql?db=" + DB, data=body,
                                 headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            try:
                doc = json.load(r)
            except ValueError:
                raise RuntimeError("gsql non-JSON response <- %s" % sql[:120])
    except urllib.error.HTTPError as e:
        try:
            detail = e.read()[:500]
        except Exception:
            detail = b""
        raise RuntimeError("gsql HTTP %s: %s <- %s"
                           % (e.code, detail, sql[:120]))
    if doc.get("code", 0) != 0 or doc.get("error"):
        raise RuntimeError("gsql failed: %s <- %s" % (doc, sql[:120]))
    return doc.get("output", [])


def grecords(base, sql, timeout=120, auth=None):
    """Row dicts in schema column order (tools/demo.py record shape)."""
    rows = []
    for out in gsql(base, sql, timeout, auth):
        rec = out.get("records")
        if rec:
            columns = [c["name"] for c in rec["schema"]["column_schemas"]]
            rows.extend(dict(zip(columns, row)) for row in rec["rows"])
    return rows


def gwait(base, timeout=300, auth=None):
    deadline = time.time() + timeout
    last_err = ""
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(base + "/health", timeout=5) as r:
                if r.status == 200:
                    gsql(base, "SELECT 1", timeout=5, auth=auth)
                    return
                last_err = "health status=%s" % r.status
        except Exception as e:  # noqa: BLE001 - surfaced on timeout
            last_err = str(e)[:200]
            time.sleep(2)
    raise RuntimeError("greptime never became healthy: %s" % last_err)


# ---- Minimal SigV4 S3 client (stdlib; bucket create + inventory LIST) ----

def _sig_headers(method, host, selector, access, secret, region,
                 payload_hash, extra=None):
    now = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    day = now[:8]
    hdrs = {"host": host, "x-amz-content-sha256": payload_hash,
            "x-amz-date": now}
    hdrs.update(extra or {})
    path, _, query = selector.partition("?")
    canon_qs = "&".join(sorted(q for q in query.split("&") if q))
    canon_hdrs = "".join("%s:%s\n" % (k, str(v).strip()) for k, v in sorted(hdrs.items()))
    signed = ";".join(sorted(hdrs))
    canon = "\n".join([method, path or "/", canon_qs, canon_hdrs, signed, payload_hash])
    scope = "%s/%s/s3/aws4_request" % (day, region)
    to_sign = "\n".join(["AWS4-HMAC-SHA256", now, scope,
                         hashlib.sha256(canon.encode()).hexdigest()])

    def h(k, m):
        return hmac.new(k, m.encode(), hashlib.sha256).digest()

    sig = hmac.new(h(h(h(h(("AWS4" + secret).encode(), day), region), "s3"),
                     "aws4_request"), to_sign.encode(), hashlib.sha256).hexdigest()
    auth = ("AWS4-HMAC-SHA256 Credential=%s/%s, SignedHeaders=%s, Signature=%s"
            % (access, scope, signed, sig))
    return {"Authorization": auth, "x-amz-date": now,
            "x-amz-content-sha256": payload_hash}


def s3_request(target, method, selector, access, secret, payload=b"",
               extra_qs="", timeout=60):
    parts = urllib.parse.urlsplit(target)
    host = parts.hostname + (":%d" % parts.port if parts.port else "")
    if extra_qs:
        selector += ("&" if "?" in selector else "?") + extra_qs
    ph = hashlib.sha256(payload).hexdigest()
    hdrs = _sig_headers(method, host, selector, access, secret, REGION, ph)
    conn = http.client.HTTPConnection(parts.hostname, parts.port or 80, timeout=timeout)
    try:
        conn.putrequest(method, selector, skip_host=True)
        conn.putheader("Host", host)
        for k, v in hdrs.items():
            conn.putheader(k, v)
        conn.putheader("Content-Length", str(len(payload)))
        conn.endheaders(payload if payload else None)
        resp = conn.getresponse()
        body = resp.read()
        return resp.status, body
    finally:
        conn.close()


def s3_list_all(target, access, secret, prefix=""):
    keys = []
    token = None
    while True:
        qs = "list-type=2&prefix=" + urllib.parse.quote(prefix, safe="") + "&max-keys=1000"
        if token:
            qs += "&continuation-token=" + urllib.parse.quote(token, safe="")
        status, body = s3_request(target, "GET", "/%s" % BUCKET, access, secret,
                                  extra_qs=qs)
        if status != 200:
            raise RuntimeError("LIST failed status=%s" % status)
        root = ET.fromstring(body)
        ns = {"s": "http://s3.amazonaws.com/doc/2006-03-01/"}
        for c in root.findall("s:Contents", ns):
            keys.append((c.find("s:Key", ns).text,
                         int(c.find("s:Size", ns).text)))
        t = root.find("s:NextContinuationToken", ns)
        if root.find("s:IsTruncated", ns) is not None and \
                root.find("s:IsTruncated", ns).text == "true" and t is not None:
            token = t.text
        else:
            return keys


