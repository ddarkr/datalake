def check_relative(cur, base, budget=None):
    """Relative regression: growth beyond the budget tolerance fails.

    Bounded control noise is credited explicitly via the budget policy's
    uncertainty_bytes/uncertainty_requests (added to the baseline before
    the compare). Explicit 0 means zero tolerance: test_relative_growth
    (100% doubling) and test_uncertainty no-credit (15% > 10%) fail;
    test_uncertainty credited (1150 vs 1100 = 4.5%) passes. Payload-zero
    must stay zero: any positive byte/request count against a credited
    zero baseline fails.
    """
    b = dict(budget or {})
    tol = Decimal(str(b.get("relative_growth_max", REL_TOL)))
    ub = Decimal(str(b.get("uncertainty_bytes", 0)))
    ur = Decimal(str(b.get("uncertainty_requests", 0)))
    if any(not v.is_finite() or v < 0 for v in (tol, ub, ur)):
        raise ValueError("relative budget must be finite and nonnegative")
    fails, notes = [], []
    for k, unc in (("read_bytes", ub), ("write_bytes", ub),
                    ("compacted_bytes", ub), ("cold_get_bytes", ub),
                    ("warm_get_bytes", ub), ("total_requests", ur)):
        c = Decimal(str(cur[k]))
        bv = Decimal(str(base[k]))
        if any(not v.is_finite() or v < 0 for v in (c, bv)):
            raise ValueError("invalid relative metric %s" % k)
        if bv == 0 and c > 0 and k != "total_requests":
            fails.append("%s baseline0 grew to %s" % (k, c))
            continue
        base_v = bv + unc
        if base_v == 0:
            if c > 0:
                fails.append("%s baseline0 grew to %d" % (k, c))
            continue
        growth = (c - base_v) / base_v
        if c > base_v and (c - base_v) >= tol * base_v:
            fails.append("%s grew %.1f%% (%d->%d, tol %.0f%%)" % (
                k, 100 * growth, bv, c, 100 * tol))
        else:
            notes.append("%s ok (%.1f%%)" % (k, 100 * growth))
    return fails, notes


def check_budget(scenario, budget_path):
    """CostGate `greptime` section: max_* absolute bounds + params."""
    if not budget_path:
        return {"status": "not-checked"}, {}
    from tools import check_cost_budget as checker
    budget = checker.load_policy(budget_path)
    g = budget["greptime"]
    if not isinstance(g, dict):
        return {"status": "not-applicable",
                "note": "no greptime section in budget"}, {}
    keymap = {"max_sst_bytes": "compacted_bytes",
              "max_requests": "total_requests",
              "max_cold_get_bytes": "cold_get_bytes",
              "max_warm_get_bytes": "warm_get_bytes"}
    fails = []
    for key, metric in keymap.items():
        bound = g.get(key)
        got = scenario.get(metric)
        if not checker.num(bound) or not checker.num(got):
            fails.append("missing/invalid %s or %s" % (key, metric))
        elif got > bound:
            fails.append("%s %s exceeds budget %s" % (metric, got, bound))
    return ({"status": "fail" if fails else "pass", "failures": fails}, g)


def main(argv=None):
    ap = argparse.ArgumentParser(description="isolated Greptime storage bench")
    ap.add_argument("--baseline-root", default=None)
    ap.add_argument("--rows", type=int, default=20000)
    ap.add_argument("--json-out", required=True)
    ap.add_argument("--budget", default=os.path.join(REPO, "config", "cost-budget.json"))
    ap.add_argument("--no-baseline", action="store_true")
    ap.add_argument("--baseline-budget", default=None)
    ap.add_argument("--greptime-image", default=None)
    ap.add_argument("--minio-binary-url", default=None,
                    help="override MinIO download base (tests only); "
                         "production default is the pinned release URL")
    a = ap.parse_args(argv)
    if a.rows <= 0:
        fail_out(a.json_out, error="--rows must be positive")
        return 1
    if not a.baseline_root and not a.no_baseline:
        fail_out(a.json_out, error="missing --baseline-root (or --no-baseline)")
        return 1
    if a.baseline_root and not os.path.isdir(a.baseline_root):
        fail_out(a.json_out, error="baseline root missing: %s" % a.baseline_root)
        return 1
    policy_note = "bootstrap: no baseline policy supplied"
    try:
        from tools import check_cost_budget as checker
        candidate = checker.load_policy(a.budget)
        base_budget = a.baseline_budget
        if not base_budget and a.baseline_root:
            path = os.path.join(a.baseline_root, "config", "cost-budget.json")
            if os.path.isfile(path):
                base_budget = path
        if base_budget:
            base_policy = checker.load_policy(base_budget)
            relaxations = checker.compare_policy(candidate, base_policy)
            if relaxations:
                raise ValueError("; ".join(relaxations))
            policy_note = "candidate constrained by baseline policy"
        require_local_docker()
    except Exception as e:
        fail_out(a.json_out, error="pre-run policy/locality: " + _redact(str(e)))
        return 1
    global MINIO_BASE
    if a.minio_binary_url:
        MINIO_BASE = a.minio_binary_url
    doc = {"benchmark": "greptime_storage", "rows": a.rows,
           "policy_note": policy_note,
           "greptime_image_default": GREPTIME_IMAGE_DEFAULT,
           "python_image_default": PYTHON_IMAGE_DEFAULT,
           "minio_pin": MINIO_PIN, "minio_sha256": MINIO_SHA256}
    variants = [("current", REPO)]
    if a.baseline_root:
        variants.append(("baseline", a.baseline_root))
    results, cleanups = {}, {}
    failed = None
    for label, root in variants:
        try:
            stage, cleanup = run_phase(label, root, a.rows, a.greptime_image)
            results[label] = stage
            cleanups[label] = cleanup
            if stage.get("status") != "success":
                failed = "%s: %s" % (label, stage.get("error", "unknown"))
                break
        except Exception as e:  # noqa: BLE001 - evidence JSON must record it
            # run_phase already tore down owned resources; record residuals.
            results[label] = {"label": label, "status": "failure",
                              "error": str(e)[:500]}
            cleanups[label] = _noop_cleanup
            failed = "%s: %s" % (label, e)
            break
    # Cleanup owned projects only; residuals are part of the evidence.
    for label, cleanup in cleanups.items():
        try:
            left_v, left_c = cleanup()
        except Exception as e:  # noqa: BLE001
            left_v, left_c = ["cleanup-error: %s" % e], []
        if label in results and isinstance(results[label], dict):
            ev = results[label].setdefault("evidence", {})
            ev.setdefault("cleanup", {"residual_volumes": left_v,
                                      "residual_containers": left_c})
        if not results[label].get("evidence", {}).get("cleanup", {}).get("success", False):
            failed = "%s owned-resource cleanup failed" % label
    if failed is not None:
        doc.update(results)
        doc["status"] = "failure"
        doc["error"] = failed[:500]
        with open(a.json_out, "w", encoding="utf-8") as f:
            json.dump(doc, f, indent=2, sort_keys=True)
        return 1
    cur_s = scenario_of(results["current"])
    doc.update(results)
    doc["greptime_storage"] = cur_s
    exit_code = 0
    budget_params = {}
    try:
        doc["budget_check"], budget_params = check_budget(cur_s, a.budget)
        if doc["budget_check"].get("status") == "fail":
            doc["status"] = "failure"
            doc["error"] = "budget exceeded: " + "; ".join(
                doc["budget_check"]["failures"])
            exit_code = 1
    except Exception as e:  # noqa: BLE001 - bad budget file fails closed
        doc["budget_check"] = {"status": "error", "error": str(e)[:300]}
        doc["status"] = "failure"
        doc["error"] = "budget file unreadable"
        exit_code = 1
    if "baseline" in results:
        if results["baseline"].get("status") != "success":
            doc["status"] = "failure"
            doc["error"] = "baseline bench failed"
            exit_code = 1
        else:
            base_s = scenario_of(results["baseline"])
            doc["baseline_greptime_storage"] = base_s
            fails, notes = check_relative(cur_s, base_s, budget_params)
            doc["comparison"] = {"failures": fails, "notes": notes}
            if fails:
                doc["status"] = "failure"
                doc["error"] = "relative regression: " + "; ".join(fails)
                exit_code = 1
    # No skipped-step success: every required stage must read success.
    for label in results:
        r = results[label]
        if not (r.get("status") == "success" and r.get("cold")
                and r.get("compact", {}).get("completed_proven")
                and r.get("warm") and r.get("warm", {}).get("reuse_proven")
                and r.get("warm", {}).get("cold_warm_equal")
                and r.get("warm", {}).get("raw_rollup_agree")
                and r.get("cold", {}).get("oracle_pass")
                and r.get("warm", {}).get("oracle_pass")
                and len(r.get("cold", {}).get("queries", [])) == 20):
            doc["status"] = "failure"
            doc["error"] = "%s missing a required stage" % label
            exit_code = 1
    doc.setdefault("status", "success")
    with open(a.json_out, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=2, sort_keys=True)
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
